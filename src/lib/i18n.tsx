const dict: Record<Lang, Record<Key, string>> = { en, pt };

type Vars = Record<string, string | number>;

interface Ctx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: Key, vars?: Vars) => string;
  /** Translate a tag such as "stun" or "dr:15" produced by the ranking model. */
  tag: (raw: string) => string;
  /** "November 11, 2026" -> localized date. */
  date: (s: string) => string;
  /** Translate generic patch titles such as "Balance Update 2.1.2". */
  patch: (title: string) => string;
  num: (n: number, digits?: number) => string;
}

const I18nContext = createContext<Ctx | null>(null);

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('arena-lang');
    if (saved === 'en' || saved === 'pt') return saved;
  } catch { /* storage unavailable */ }
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

const PATCH_WORDS: [RegExp, string][] = [
  [/Pre-Season Starts/gi, 'Início da Pré-Temporada'],
  [/Balance Update/gi, 'Atualização de Balanceamento'],
  [/Major Update/gi, 'Grande Atualização'],
  [/Major Balance/gi, 'Grande Balanceamento'],
  [/New Characters/gi, 'Novos Personagens'],
];

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);

  useEffect(() => {
    document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try { localStorage.setItem('arena-lang', l); } catch { /* ignore */ }
  }, []);

  const value = useMemo<Ctx>(() => {
    const locale = lang === 'pt' ? 'pt-BR' : 'en-US';
    const t: Ctx['t'] = (key, vars) => {
      let s: string = dict[lang][key] ?? en[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
      return s;
    };
    return {
      lang, setLang, t,
      tag: (raw) => {
        const [k, a, b, c] = raw.split('|');
        if (k === 'kind') return t(('tag.kind.' + a) as Key);
        if (k === 'stack') return t('tag.stack', { a, b: t(('stat.' + b) as Key), c });
        return t(('tag.' + k) as Key, { a, b, c });
      },
      date: (s) => {
        const d = new Date(s);
        return Number.isNaN(d.getTime()) ? s : d.toLocaleDateString(locale, { year: 'numeric', month: 'long', day: 'numeric' });
      },
      patch: (title) => (lang === 'pt' ? PATCH_WORDS.reduce((a, [re, to]) => a.replace(re, to), title) : title),
      num: (n, digits = 0) => n.toLocaleString(locale, { minimumFractionDigits: digits, maximumFractionDigits: digits }),
    };
  }, [lang, setLang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
